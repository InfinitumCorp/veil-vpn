// Infinitum app icons: black letters in the brand font on a white background, with ™ set like
// the wordmark's superscript. One file draws every product's mark:
//   veil "V |™"   cumulus "://™"   fabric "F++™"   scalvs "S™"
// The letters are the brand font's glyph outlines (scripts/icon-glyphs.json): the brand stack
// "Helvetica Neue", Helvetica, Arial at the wordmark's weight (regular Arial here); ™ at .38em
// with its top on cap height.
//
//   node scripts/icon.mjs                 VEIL: veil-vpn/icon.svg, site/icon.svg, the Android launcher
//                                         (adaptive icon in res/drawable) and store/play/images/icon-512.png
//   node scripts/icon.mjs <mark> <dir>    any mark: icon.svg, icon-<px>.png and an Android res/drawable tree in <dir>
// scripts/build.mjs draws VEIL's extension PNGs with pngIcon().
import { mkdirSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import GLYPHS from './icon-glyphs.json' with { type: 'json' };

/** The mark's outlines in a 512 grid: 72% of the width (or 52% of the height), centred. */
export function layout(name) {
  const g = GLYPHS[name];
  if (!g) throw new Error(`unknown mark ${name}`);
  const pts = g.flat(), xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
  const x0 = Math.min(...xs), x1 = Math.max(...xs), y0 = Math.min(...ys), y1 = Math.max(...ys);
  const s = Math.min((512 * 0.72) / (x1 - x0), (512 * 0.52) / (y1 - y0));
  const ox = 256 - ((x0 + x1) / 2) * s, oy = 256 - ((y0 + y1) / 2) * s;
  return g.map((c) => c.map(([x, y]) => [ox + x * s, oy + y * s]));
}

// Even-odd fill over all contours (handles counters if a mark ever has one).
const inGlyphs = (C, x, y) => {
  let c = false;
  for (const poly of C) for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};

function crc32(buf) {
  let c, crc = ~0;
  for (const b of buf) { c = (crc ^ b) & 255; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; crc = (crc >>> 8) ^ c; }
  return ~crc >>> 0;
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
};

/** PNG at size x size: black letters on white, 6x6 supersampled. */
export function pngIcon(size, name = 'veil') {
  const C = layout(name), N = 6, k = 512 / size, raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0;
    for (let x = 0; x < size; x++) {
      let ink = 0;
      for (let sy = 0; sy < N; sy++) for (let sx = 0; sx < N; sx++) {
        if (inGlyphs(C, (x + (sx + 0.5) / N) * k, (y + (sy + 0.5) / N) * k)) ink++;
      }
      const i = y * (size * 4 + 1) + 1 + x * 4;
      raw[i] = raw[i + 1] = raw[i + 2] = Math.round(255 * (1 - ink / (N * N)));
      raw[i + 3] = 255;
    }
  }
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}

const r = (n) => +n.toFixed(2);
const pathData = (name, k = 1, off = 0) => layout(name).map((c) => c.map(([x, y], i) => `${i ? 'L' : 'M'}${r(off + x * k)} ${r(off + y * k)}`).join('') + 'Z').join('');

export function svgIcon(name = 'veil') {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><rect width="512" height="512" fill="#fff"/>`
    + `<path fill="#000" fill-rule="evenodd" d="${pathData(name)}"/></svg>\n`;
}

/**
 * Android launcher as an adaptive icon in res/drawable: white background, the black mark as the
 * foreground, and the same mark as the monochrome layer (launchers that theme icons, such as
 * THRONE][OS, draw that layer as black letters on white). The 512 grid maps onto the 66dp safe zone.
 */
export function writeAndroidRes(resDir, name) {
  const dir = path.join(resDir, 'drawable');
  mkdirSync(dir, { recursive: true });
  const head = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/icon.mjs: black letters in the brand font on white. -->\n';
  const vec = (body) => `${head}<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp" android:height="108dp"\n    android:viewportWidth="108" android:viewportHeight="108">\n${body}</vector>\n`;
  writeFileSync(path.join(dir, 'ic_launcher_background.xml'), vec('    <path android:fillColor="#FFFFFFFF" android:pathData="M0,0h108v108h-108z" />\n'));
  writeFileSync(path.join(dir, 'ic_launcher_mark.xml'), vec(`    <path android:fillColor="#FF000000" android:fillType="evenOdd" android:pathData="${pathData(name, 66 / 512, 21)}" />\n`));
  writeFileSync(path.join(dir, 'ic_launcher.xml'), `${head}<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n`
    + '    <background android:drawable="@drawable/ic_launcher_background" />\n'
    + '    <foreground android:drawable="@drawable/ic_launcher_mark" />\n'
    + '    <monochrome android:drawable="@drawable/ic_launcher_mark" />\n</adaptive-icon>\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [name, dir] = process.argv.slice(2);
  if (name) {
    if (!dir) throw new Error('usage: node scripts/icon.mjs <veil|cumulus|fabric|scalvs> <dir>');
    mkdirSync(dir, { recursive: true });
    writeFileSync(path.join(dir, 'icon.svg'), svgIcon(name));
    for (const s of [16, 32, 48, 96, 192, 512]) writeFileSync(path.join(dir, `icon-${s}.png`), pngIcon(s, name));
    writeAndroidRes(path.join(dir, 'res'), name);
    console.log(`Wrote the ${name} icon set to ${dir}`);
  } else {
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
    const p = (...x) => path.join(root, ...x);
    for (const f of ['veil-vpn/icon.svg', 'site/icon.svg']) writeFileSync(p(f), svgIcon('veil'));
    writeFileSync(p('store/play/images/icon-512.png'), pngIcon(512, 'veil'));
    writeAndroidRes(p('android/app/src/main/res'), 'veil');
    console.log('Wrote icon.svg (app and site), the Android adaptive launcher icon and the 512 px store icon');
  }
}
